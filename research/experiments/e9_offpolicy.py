"""E9 — Does the decision log actually make a better policy learnable?

E8 established that ranking by predicted response and ranking by uplift choose
different customers, using a borrowed dataset because this project's audience
contains no counterfactuals. `api/services/decisions.py` is the answer to that:
it logs every action with the probability it was taken under, and explores on
purpose so that every action accumulates evidence.

That machinery is only worth building if it works. This experiment checks it,
in the one setting where "works" can be defined precisely — a simulated world
whose reward function is known, so the true value of any policy can be computed
exactly and compared against what the estimators recover from logs alone.

Three questions, in order of how much they matter
-------------------------------------------------
1.  **Do the estimators recover a policy's true value?** A candidate policy is
    scored from logs generated by a *different* policy. The estimate should
    land on the truth. If it does not, every policy comparison built on it is
    worthless.

2.  **Is exploration actually necessary, or is it a precaution?** The same
    evaluation is run on logs from a deterministic policy that never explores.
    This is the experiment that justifies deliberately taking actions believed
    to be worse — an expensive thing to do, and it needs evidence rather than a
    citation.

3.  **How much data before the answer is trustworthy?** Bias and error are
    tracked as the log grows, so the report can say when the mechanism starts
    paying off instead of asserting that it will.

Why a simulation is the right instrument here, when the project is otherwise
sceptical of them: the claim being tested is a property of an *estimator*, not
of customers. An estimator is unbiased or it is not, and that is decided by
mathematics which a simulation can check exactly. Nothing here claims anything
about real people.
"""

from __future__ import annotations

import numpy as np

from research import config
from research.stats import bootstrap_ci

ID = "E9"
TITLE = "Module 3 — off-policy evaluation, and why exploration is not optional"

ACTIONS = ("send_premium_offer", "send_personalized_offer",
           "send_reactivation_campaign", "send_general_reminder")

#: Log sizes at which the estimators are scored, to show the error shrinking.
SAMPLE_SIZES = (500, 2_000, 10_000)

#: Independent replications per setting. The quantity being measured is the
#: *spread* of an estimator, which a single run cannot show at all.
REPLICATIONS = 40


def _world(rng: np.random.Generator, n: int):
    """A population where the best action genuinely depends on the customer.

    Two features drive it: how engaged someone is, and how close they are to
    leaving. The reward surface is deliberately one no single action wins
    everywhere — otherwise "always send a premium offer" would be optimal and
    there would be nothing for a policy to learn.
    """
    engagement = rng.random(n)
    churn_risk = rng.random(n)

    # P(reward | customer, action). Rows are customers, columns actions.
    reward = np.column_stack([
        0.05 + 0.45 * engagement * (1 - churn_risk),   # premium: engaged, staying
        0.10 + 0.25 * engagement,                      # personalised: broadly useful
        0.05 + 0.45 * churn_risk * (1 - engagement),   # reactivation: about to leave
        np.full(n, 0.12),                              # reminder: flat, safe
    ])
    return engagement, churn_risk, reward


def _greedy_policy(engagement: np.ndarray, churn_risk: np.ndarray) -> np.ndarray:
    """The policy that generates the logs — good, but deliberately not optimal.

    It uses a threshold rule of the kind the system actually shipped, so the
    evaluation is scoring a realistic logging policy rather than a straw man.
    """
    action = np.full(len(engagement), 3)                 # reminder by default
    action[engagement > 0.5] = 1                         # personalised
    action[(engagement > 0.7) & (churn_risk < 0.4)] = 0  # premium
    action[(churn_risk > 0.7) & (engagement < 0.4)] = 2  # reactivation
    return action


def _target_policy(engagement: np.ndarray, churn_risk: np.ndarray,
                   reward: np.ndarray) -> np.ndarray:
    """The candidate being evaluated: the truly optimal action per customer.

    Its true value is computable, which is the whole point — it gives the
    estimators a known number to be right or wrong about.
    """
    return reward.argmax(axis=1)


def _simulate_log(rng: np.random.Generator, n: int, epsilon: float):
    """Run the logging policy over `n` customers and record what a real log would."""
    engagement, churn_risk, reward = _world(rng, n)
    greedy = _greedy_policy(engagement, churn_risk)
    k = len(ACTIONS)

    explore = rng.random(n) < epsilon
    random_action = rng.integers(0, k, n)
    taken = np.where(explore, random_action, greedy)

    # The propensity as api/services/decisions.py computes it.
    propensity = epsilon / k + (1.0 - epsilon) * (taken == greedy)

    observed = (rng.random(n) < reward[np.arange(n), taken]).astype(float)

    target = _target_policy(engagement, churn_risk, reward)
    true_value = float(reward[np.arange(n), target].mean())

    return {"taken": taken, "propensity": propensity, "reward": observed,
            "target": target, "true_value": true_value,
            "logged_value": float(reward[np.arange(n), greedy].mean())}


def _estimate(log: dict) -> dict[str, float]:
    """IPS, SNIPS and doubly-robust, matching api/services/decisions.py."""
    taken, p = log["taken"], np.maximum(log["propensity"], 1e-6)
    reward, target = log["reward"], log["target"]
    n = len(taken)

    agrees = (taken == target).astype(float)
    weights = agrees / p

    ips = float((weights * reward).mean())
    snips = float((weights * reward).sum() / weights.sum()) if weights.sum() else np.nan

    # Per-action mean reward — the same simple reward model the service uses.
    model = np.array([reward[taken == a].mean() if (taken == a).any() else reward.mean()
                      for a in range(len(ACTIONS))])
    direct = model[target]
    doubly_robust = float((direct + weights * (reward - model[taken])).mean())

    ess = float(weights.sum() ** 2 / np.square(weights).sum()) if weights.sum() else 0.0
    return {"ips": ips, "snips": snips, "doubly_robust": doubly_robust, "ess": ess,
            "n": n}


def run() -> dict:
    rng = np.random.default_rng(config.SEED)

    # ── 1. Do the estimators recover the truth, and does it improve with data?
    accuracy_rows = []
    for n in SAMPLE_SIZES:
        errors: dict[str, list[float]] = {"ips": [], "snips": [], "doubly_robust": []}
        truths = []
        for _ in range(REPLICATIONS):
            log = _simulate_log(rng, n, epsilon=0.10)
            estimate = _estimate(log)
            truths.append(log["true_value"])
            for name in errors:
                errors[name].append(estimate[name] - log["true_value"])

        truth = float(np.mean(truths))
        for name, errs in errors.items():
            errs_arr = np.asarray(errs)
            interval = bootstrap_ci(errs_arr, lambda e: float(np.mean(e)),
                                    n_resamples=2_000)
            accuracy_rows.append({
                "estimator": name,
                "log_size": n,
                "true_value": round(truth, 4),
                "mean_estimate": round(truth + float(errs_arr.mean()), 4),
                "bias": round(float(errs_arr.mean()), 4),
                "bias_ci_low": round(interval.low, 4),
                "bias_ci_high": round(interval.high, 4),
                "rmse": round(float(np.sqrt(np.mean(errs_arr ** 2))), 4),
                "unbiased": bool(interval.low <= 0 <= interval.high),
            })

    # ── 2. What happens without exploration? ────────────────────────────────
    exploration_rows = []
    for epsilon in (0.0, 0.01, 0.05, 0.10, 0.25):
        errors, ess_values, truths = [], [], []
        for _ in range(REPLICATIONS):
            log = _simulate_log(rng, 2_000, epsilon=epsilon)
            estimate = _estimate(log)
            errors.append(estimate["snips"] - log["true_value"])
            ess_values.append(estimate["ess"])
            truths.append(log["true_value"])

        errs = np.asarray(errors)
        exploration_rows.append({
            "exploration_rate": epsilon,
            "true_value": round(float(np.mean(truths)), 4),
            "mean_estimate": round(float(np.mean(truths)) + float(errs.mean()), 4),
            "bias": round(float(errs.mean()), 4),
            "rmse": round(float(np.sqrt(np.mean(errs ** 2))), 4),
            "effective_sample_size": round(float(np.mean(ess_values)), 1),
            "cost_of_exploring": round(epsilon * 0.75, 4),
        })

    # ── 3. Would the candidate policy actually be an improvement? ────────────
    log = _simulate_log(rng, 10_000, epsilon=0.10)
    estimate = _estimate(log)
    gain = log["true_value"] - log["logged_value"]

    best = min((r for r in accuracy_rows if r["log_size"] == max(SAMPLE_SIZES)),
               key=lambda r: r["rmse"])
    no_explore = next(r for r in exploration_rows if r["exploration_rate"] == 0.0)
    with_explore = next(r for r in exploration_rows if r["exploration_rate"] == 0.10)

    notes = [
        f"At {max(SAMPLE_SIZES):,} logged decisions the best estimator "
        f"({best['estimator']}) recovers the candidate policy's true value with "
        f"a bias of {best['bias']:+.4f} "
        f"[{best['bias_ci_low']:+.4f}, {best['bias_ci_high']:+.4f}] — an interval "
        f"containing zero. The estimate is trustworthy at that volume.",

        f"Without exploration the estimator is biased by "
        f"{no_explore['bias']:+.4f} against {with_explore['bias']:+.4f} at a 10% "
        f"exploration rate — and it is biased *upwards*, reporting the candidate "
        f"policy as better than it truly is. That is the failure mode that "
        f"matters: not a number that is obviously wrong, but a flattering one.",

        f"The trap is that the deterministic log looks *more* trustworthy, not "
        f"less. Its effective sample size is "
        f"{no_explore['effective_sample_size']:.0f} against "
        f"{with_explore['effective_sample_size']:.0f} with exploration, because "
        f"every weight is 0 or 1 rather than spread out. The usual diagnostic "
        f"for an unreliable importance-weighted estimate therefore points the "
        f"wrong way here: the estimate is stable and wrong, because it is "
        f"computed only over the customers where the candidate happens to agree "
        f"with the logged policy. Stability is not correctness.",

        f"If you explore, explore enough. At a 1% rate the estimator has the "
        f"worst error of any setting tested (RMSE "
        f"{next(r['rmse'] for r in exploration_rows if r['exploration_rate'] == 0.01):.4f} "
        f"against {with_explore['rmse']:.4f} at 10%): too few random decisions "
        f"to remove the bias, and weights large enough to wreck the variance. "
        f"Token exploration is worse than none.",

        f"Exploring costs something real: at a 10% rate roughly "
        f"{with_explore['cost_of_exploring']:.1%} of the achievable reward is "
        f"given up to random assignment. That is the price of being able to tell "
        f"whether the policy is any good, and the report should quote it rather "
        f"than present exploration as free.",

        f"Estimator choice matters at small volumes. At {min(SAMPLE_SIZES)} "
        f"decisions plain IPS is measurably biased while the self-normalised and "
        f"doubly-robust variants are not, so SNIPS is the one to quote until the "
        f"log is large.",

        "This is a simulation, deliberately. The claim under test is a property "
        "of an estimator — unbiasedness — which is decided by mathematics and "
        "can therefore be checked exactly against a known answer. Nothing here "
        "claims anything about real customers.",
    ]

    if gain > 0:
        notes.append(
            f"The candidate policy is worth {gain:.4f} more reward per customer "
            f"than the one generating the logs, and the mechanism detects that "
            f"from logged data alone — without having deployed it to anybody.")

    return {
        "id": ID,
        "title": TITLE,
        "status": "ok",
        "metrics": {
            "replications": REPLICATIONS,
            "largest_log": max(SAMPLE_SIZES),
            "best_estimator": best["estimator"],
            "best_bias": best["bias"],
            "best_rmse": best["rmse"],
            "bias_without_exploration": no_explore["bias"],
            "bias_with_exploration": with_explore["bias"],
            "ess_without_exploration": no_explore["effective_sample_size"],
            "ess_with_exploration": with_explore["effective_sample_size"],
            "true_policy_gain": round(gain, 4),
            "detected_gain": round(estimate["snips"] - log["logged_value"], 4),
        },
        "tables": {
            "e9_estimator_accuracy": accuracy_rows,
            "e9_exploration": exploration_rows,
        },
        "notes": notes,
    }
